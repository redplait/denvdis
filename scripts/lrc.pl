sub process {
  my($str);
  my $status = 0;
  while( $str = <> ) {
    if ( !$status ) {
      if ( $str =~ /\.weak\s+\.func\s+.*(cuda\w+)/ ) {
        if ( exists $cfs{$1} ) {
          $status = 1;
          next;
        }
      }
      print $str;
      next;
    }
    # check -- End function
    if ( $str =~ /-- End function/ ) {
      $status = 2;
      next;
    }
    if ( 2 == $status && $str =~ /\}/ ) {
      $status = 0;
      next;
    }
  }
}

# main
my $status = getopts("c");
usage() if ( !$status );
if ( 1 == $#ARGV ) {
  printf("where is arg?\n");
  exit(5);
}
if ( defined $opt_c ) {
  gen_crt();
} else {
  process();
}
