}

sub gen_crt {
  my($str, %names);
  while( $str = <> ) {
    chomp $str;
    if ( $str =~ /CUDARTAPI\s+([^\(]+)\s*\(/ ) {
      $names{$1}++;
      next;
    }
  }
  # dump in perl format
  foreach my $n ( sort keys %names ) {
    printf(" %s => 1,\n", $n);
  }
}

